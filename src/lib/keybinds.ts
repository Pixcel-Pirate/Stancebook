/**
 * Suggested keybinds per class, in the style of muhshuh's "Keybinds Guide - WoW" (Classic Hunter and
 * Rogue layouts): WASD to move with Q/E strafing, the rotation on 1–5 and Shift+1–5, the keys around
 * WASD (R F G T V C X Z) plus their Shift versions, openers and marks on the mouse wheel, melee and
 * fillers on Mouse 4/5, trinket and racial on the middle button, Z mount, Shift+Tab bandage.
 * Ability names must match src/lib/abilities.ts or GENERIC (scripts/keybinds.check.ts).
 */
export type Bind = [key: string, ability: string, note?: string];
export type BindGroup = { title: string; hint: string; binds: Bind[] };

const g = (name: string, icon: string, desc: string): Ability => ({ name, icon, meta: "Not a spell", desc });
