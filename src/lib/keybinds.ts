/**
 * Suggested keybinds per class. Every class follows the same plan so muscle memory carries over:
 * rotation on 1–5 / Q / E (closest to WASD), interrupt or stun on F, "get out of trouble" on V,
 * situational spells on Shift+, emergency cooldowns on the mouse side buttons, buffs and other
 * out-of-combat spells on Ctrl+. Ability names must match src/lib/abilities.ts (scripts/keybinds.check.ts).
 */
