const SORTED = [...SPELL_FR].sort((a, b) => b[0].length - a[0].length);

export type ClientLang = "en" | "fr";

export function localizeMacro(source: string, lang: ClientLang): string {
  if (lang === "en") return source;
  let out = source;
  for (const [en, fr] of SORTED) {
    out = out.split(en).join(fr);
  }
  return out;
}

export function charCount(source: string, lang: ClientLang): number {
  return localizeMacro(source, lang).length;
}
